"""Play every built-in against every other and write docs/balance.md.

    uv run python scripts/balance_report.py --seed-pairs 50

The report answers the Phase 2 questions: does either seat have an advantage, does any
strategy beat everything, and do greed, aggression and defence counter each other?
"""

import argparse
import logging
import os
import statistics
from collections import Counter
from datetime import date
from pathlib import Path

from arena.builtin import BUILTINS
from arena.tournament import Game, round_robin, standing, table, wilson
from arena_engine import ENGINE_VERSION

log = logging.getLogger(__name__)
OUT = Path(__file__).resolve().parent.parent / "docs" / "balance.md"
PURE = ["builtin:greedy", "builtin:rush", "builtin:turtle"]


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0] if __doc__ else None)
    parser.add_argument("--seed-pairs", type=int, default=50)
    parser.add_argument("--jobs", type=int, default=os.cpu_count() or 1)
    args = parser.parse_args()

    bots = [f"builtin:{name}" for name in BUILTINS]
    log.info("playing %d games", len(bots) * (len(bots) - 1) * args.seed_pairs)
    games = round_robin(bots, args.seed_pairs, args.jobs)
    OUT.write_text(report(games, bots, args.seed_pairs))
    log.info("wrote %s", OUT)


def report(games: list[Game], bots: list[str], seed_pairs: int) -> str:
    seat0 = sum(
        1.0 if g.result.winner == 0 else 0.5 if g.result.winner is None else 0.0 for g in games
    )
    lo, hi = wilson(seat0, len(games))
    lengths = sorted(g.result.turns for g in games)
    reasons = Counter(g.result.reason for g in games)
    draws = sum(g.result.winner is None for g in games)

    def name(bot: str) -> str:
        return bot.removeprefix("builtin:")

    dominant = [
        name(b)
        for b in bots
        if all(standing(games, b, o).interval()[0] > 0.5 for o in bots if o != b)
    ]
    beats = {
        (name(a), name(b)): standing(games, a, b).interval()[0] > 0.5
        for a in PURE
        for b in PURE
        if a != b
    }
    cycle = [f"{a} beats {b}" for (a, b), won in beats.items() if won]
    q = statistics.quantiles(lengths, n=4)
    checks = "\n".join(
        [
            "| Check | Result | Target |",
            "|---|---|---|",
            f"| Seat 0 score | {seat0 / len(games):.1%} [{lo:.1%}, {hi:.1%}] "
            "| interval contains 50% |",
            f"| A bot beats every other bot | {', '.join(dominant) or 'none'} "
            "| none, or only the adaptive `scout` |",
            f"| Pure strategies (greedy, rush, turtle) | {'; '.join(cycle) or 'no clear wins'} "
            "| a cycle: each beats one, loses to one |",
        ]
    )

    return f"""# Balance report

Generated by `scripts/balance_report.py --seed-pairs {seed_pairs}` on {date.today()}, engine
{ENGINE_VERSION}. Every pairing of built-in bots played {seed_pairs} maps from both seats:
{len(games)} games. Scores count a win as 1 and a draw as 0.5. Intervals are 95% Wilson
intervals.

## Win matrix

Each cell is the row bot's score against the column bot.

```
{table(games, bots)}
```

## The Phase 2 checks

{checks}

## Shape of the games

- Draws: {draws} of {len(games)} ({draws / len(games):.1%})
- How games ended: {", ".join(f"{r} {n}" for r, n in reasons.most_common())}
- Game length: median {statistics.median(lengths):.0f} turns, quartiles {q[0]:.0f} / {q[2]:.0f},
  shortest {lengths[0]}, longest {lengths[-1]}
"""


if __name__ == "__main__":
    logging.basicConfig(level=logging.INFO, format="%(message)s")
    main()
